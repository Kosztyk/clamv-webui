package info.trizub.clamav.webclient.service;

import java.time.Instant;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Non-sensitive ClamD STATS projection shared by v1, legacy API, and the viewer UI. Deliberately
 * uses an allowlist: never copy raw STATS, commands, queued paths, endpoint host/name, daemon error
 * messages, or unparsed lines into this map.
 */
public final class ClamdMetricsView {
  private ClamdMetricsView() {}

  public static Map<String, Object> from(Map<String, Object> snapshot, Long endpointId) {
    Map<?, ?> parsed = snapshot.get("parsed") instanceof Map<?, ?> m ? m : Map.of();
    Map<String, Object> result = new LinkedHashMap<>();
    result.put("endpointId", endpointId);
    result.put("ok", Boolean.TRUE.equals(snapshot.get("ok")));
    result.put(
        "threads",
        safeCounts(parsed.get("threads"), List.of("live", "idle", "busy", "max", "idleTimeout")));
    result.put("queue", safeCounts(parsed.get("queue"), List.of("items", "max")));
    result.put("pools", safeCount(parsed.get("pools")));
    Map<String, String> memory = new LinkedHashMap<>();
    if (parsed.get("memory") instanceof Map<?, ?> values) {
      for (String key :
          List.of(
              "heap", "mmap", "used", "free", "releasable", "pools", "pools_used", "pools_total")) {
        Object value = values.get(key);
        if (value != null
            && value.toString().matches("(?i)(?:[0-9]+(?:\\.[0-9]+)?[KMGT]?(?:I?B)?|N/A)"))
          memory.put(key, value.toString());
      }
    }
    result.put("memory", memory);
    // Source snapshot timestamps are generated by this service; do not copy arbitrary daemon
    // strings.
    Object stamp = snapshot.get("timestamp");
    result.put(
        "checkedAt",
        stamp instanceof String text && text.matches("[0-9TZ: .+\\-]{10,50}")
            ? text
            : Instant.now().toString());
    return result;
  }

  public static String summary(Map<String, Object> view) {
    Map<?, ?> threads = view.get("threads") instanceof Map<?, ?> m ? m : Map.of();
    Map<?, ?> queue = view.get("queue") instanceof Map<?, ?> m ? m : Map.of();
    if (!Boolean.TRUE.equals(view.get("ok"))) return "ClamD health information is unavailable.";
    return "Threads: live="
        + display(threads.get("live"))
        + " busy="
        + display(threads.get("busy"))
        + " idle="
        + display(threads.get("idle"))
        + " | Queue: "
        + display(queue.get("items"));
  }

  private static String display(Object value) {
    return value == null ? "—" : value.toString();
  }

  private static Map<String, Long> safeCounts(Object source, List<String> keys) {
    Map<String, Long> result = new LinkedHashMap<>();
    if (source instanceof Map<?, ?> values)
      for (String key : keys) {
        Long value = safeCount(values.get(key));
        if (value != null) result.put(key, value);
      }
    return result;
  }

  private static Long safeCount(Object value) {
    if (!(value instanceof Number number)) return null;
    double count = number.doubleValue();
    return Double.isFinite(count) && count >= 0 && count == number.longValue()
        ? number.longValue()
        : null;
  }
}
