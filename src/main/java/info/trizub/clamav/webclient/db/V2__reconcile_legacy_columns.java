package info.trizub.clamav.webclient.db;

import java.sql.*;
import java.util.*;
import org.flywaydb.core.api.migration.BaseJavaMigration;
import org.flywaydb.core.api.migration.Context;
import org.springframework.stereotype.Component;

/**
 * Non-destructive legacy reconciliation. Never drops/rewrites existing rows or PG Large Objects.
 * Called after operators explicitly baseline version 1 on a backed-up legacy schema.
 */
@Component
public class V2__reconcile_legacy_columns extends BaseJavaMigration {
    @Override public void migrate(Context context) throws Exception {
        Connection c = context.getConnection();
        String name = c.getMetaData().getDatabaseProductName().toLowerCase(Locale.ROOT);
        String vendor = name.contains("postgres") ? "postgresql" :
                name.contains("mariadb") ? "mariadb" : name.contains("mysql") ? "mysql" : "h2";
        for (String table : List.of("app_users", "app_user_roles", "audit_events", "clamd_endpoints",
                "scan_jobs", "watched_directories", "processed_files")) {
            if (!exists(c, table, null)) {
                throw new SQLException("Legacy schema is missing " + table +
                        ". Restore/upgrade the original schema first; never baseline a partial schema.");
            }
        }
        if (vendor.equals("postgresql")) {
            for (String field : List.of("found_viruses_json", "error_message")) {
                String type = columnType(c, "scan_jobs", field);
                if (type != null && type.equalsIgnoreCase("oid")) {
                    throw new SQLException("Legacy scan_jobs." + field +
                        " is PostgreSQL OID. Flyway does NOT silently convert Large Objects. " +
                        "Back up the database and follow docs/PHASE2_DATABASE_PORTABILITY.md (manual OID remediation).");
                }
            }
        }
        if (!exists(c, "api_credentials", null)) {
            String id = vendor.equals("postgresql") || vendor.equals("h2") ?
                    "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : "BIGINT AUTO_INCREMENT PRIMARY KEY";
            String instant = vendor.equals("mysql") || vendor.equals("mariadb") ?
                    "DATETIME(6)" : "TIMESTAMP(6) WITH TIME ZONE";
            execute(c, "CREATE TABLE api_credentials (id " + id + ", label VARCHAR(100) NOT NULL, " +
                    "token_hash VARCHAR(64) NOT NULL, prefix VARCHAR(16) NOT NULL, " +
                    "scopes VARCHAR(512) NOT NULL, endpoint_ids VARCHAR(1024), " +
                    "path_roots VARCHAR(2048), created_at " + instant + " NOT NULL, " +
                    "expires_at " + instant + ", revoked_at " + instant + ", last_used_at " + instant + ")");
        }
        add(c,"audit_events", "transport", "VARCHAR(32)");
        add(c,"audit_events", "endpoint_id", "BIGINT");
        add(c,"scan_jobs", "submitted_transport", "VARCHAR(32)");
        add(c,"api_credentials", "endpoint_ids", "VARCHAR(1024)");
        add(c,"api_credentials", "path_roots", "VARCHAR(2048)");
        add(c,"api_credentials", "last_used_at", vendor.equals("mysql") || vendor.equals("mariadb") ?
                "DATETIME(6)" : "TIMESTAMP(6) WITH TIME ZONE");
        createIndex(c,"api_credentials","idx_api_credentials_hash", "token_hash",true);
        createIndex(c,"scan_jobs","idx_scan_jobs_submitted_at", "submitted_at",false);
        createIndex(c,"scan_jobs","idx_scan_jobs_status", "status",false);
        createIndex(c,"audit_events","idx_audit_at", "at",false);
        createIndex(c,"audit_events","idx_audit_job_id", "job_id",false);
        if (vendor.equals("mysql") || vendor.equals("mariadb")) {
            // Indexed full 4096-char paths exceed InnoDB maximum index bytes under utf8mb4.
            // A generated SHA-256 digest maintains uniqueness without truncating paths.
            if (!exists(c,"processed_files","path_digest")) {
                execute(c,"ALTER TABLE processed_files ADD COLUMN path_digest BINARY(32) " +
                        "GENERATED ALWAYS AS (UNHEX(SHA2(path, 256))) STORED");
            }
            createIndex(c,"processed_files","idx_processed_path_digest","path_digest",true);
        } else {
            createIndex(c,"processed_files","idx_processed_path","path",true);
        }
    }
    private void add(Connection c,String table,String column,String type) throws SQLException {
        if (!exists(c,table,column)) execute(c,"ALTER TABLE " + table + " ADD COLUMN " + column + " " + type);
    }
    private static void execute(Connection c,String sql) throws SQLException {
        try (Statement st=c.createStatement()) { st.execute(sql); }
    }
    private static boolean exists(Connection c,String table,String column) throws SQLException {
        return columnType(c,table,column)!=null;
    }
    private static String columnType(Connection c,String table,String column) throws SQLException {
        DatabaseMetaData md=c.getMetaData();
        String product=md.getDatabaseProductName().toLowerCase(Locale.ROOT);
        String schema=(product.contains("mysql") || product.contains("maria")) ? null : c.getSchema();
        for (String t:List.of(table,table.toUpperCase(Locale.ROOT))) {
            // MySQL uses catalogs rather than schemas; H2/PG use current schema.
            try (ResultSet rs=md.getColumns(c.getCatalog(),schema,t,"%")) {
                while (rs.next()) {
                    if (column==null || column.equalsIgnoreCase(rs.getString("COLUMN_NAME")))
                        return rs.getString("TYPE_NAME");
                }
            }
        }
        return null;
    }
    private void createIndex(Connection c,String table,String index,String column,boolean unique) throws SQLException {
        DatabaseMetaData md=c.getMetaData();
        String product=md.getDatabaseProductName().toLowerCase(Locale.ROOT);
        String schema=(product.contains("mysql") || product.contains("maria")) ? null : c.getSchema();
        for (String t:List.of(table,table.toUpperCase(Locale.ROOT))) {
            try (ResultSet rs=md.getIndexInfo(c.getCatalog(),schema,t,false,false)) {
                while (rs.next()) if (index.equalsIgnoreCase(rs.getString("INDEX_NAME"))) return;
            }
        }
        execute(c, "CREATE " + (unique?"UNIQUE ":"") + "INDEX " + index + " ON " + table + " ("+column+")");
    }
}
